def compute_torque(quality, mode):
    m = HW_MODES.get(mode, HW_MODES[0])
    return float(np.clip(m["scale"] * quality + m["bias"], m["min"], m["max"]))

def generate_feedback(label, quality, scalars):
    s = np.asarray(scalars)
    triggered = sorted([r for r in FEEDBACK_RULES if r["check"](s)],
                       key=lambda r: r["priority"], reverse=True)
    flags = [r["name"] for r in triggered]
    if label == 1 and quality >= 0.75:
        return {"message":"Great rep - keep it up!","short":"Great rep",
                "flags":[],"severity":"good"}
    if label == 1 and quality >= 0.5:
        return {"message":"Good rep - maintain that form.","short":"Good rep",
                "flags":flags,"severity":"good"}
    if triggered:
        top = triggered[0]
        return {"message":top["message"],"short":top["short"],
                "flags":flags,
                "severity":"error" if top["priority"] >= 8 else "warning"}
    return {"message":"Focus on smooth, controlled movement.",
            "short":"Keep it smooth","flags":[],"severity":"warning"}

def hardware_payload(sample, quality, torque, mode):
    kps    = sample["keypoints"]
    lk     = knee_angles(kps,"L"); rk = knee_angles(kps,"R")
    lp, rp = float(np.min(lk)), float(np.min(rk))
    lr, rr = float(np.max(lk)-lp), float(np.max(rk)-rp)
    ex     = sample.get("exercise","unknown")
    tgt    = TARGET_ANGLES.get(ex, TARGET_ANGLES["default"])
    return {
        "torque":            round(torque, 4),
        "mode":              HW_MODES[mode]["name"],
        "mode_int":          mode,
        "joint": {
            "left_knee_peak_deg":  round(lp, 2),
            "right_knee_peak_deg": round(rp, 2),
            "left_knee_rom_deg":   round(lr, 2),
            "right_knee_rom_deg":  round(rr, 2),
        },
        "target": {
            "knee_target_deg":   tgt,
            "left_deficit_deg":  round(max(0., tgt-lp), 2),
            "right_deficit_deg": round(max(0., tgt-rp), 2),
        },
        "torque_per_degree": round(torque / max(max(0., tgt-lp), 1.0), 5),
    }

@torch.no_grad()
def infer_sample(model, sample, ae=None, device=DEVICE, hw_mode=0):
    m_ = model.module if hasattr(model,"module") else model
    m_.eval()
    kps_t  = (torch.from_numpy(sample["keypoints"])
              .permute(2,0,1).unsqueeze(0).to(device))
    adj_t  = torch.from_numpy(ADJ).to(device)
    sc_t   = torch.from_numpy(sample["scalars"]).unsqueeze(0).to(device)
    mode_t = torch.tensor([hw_mode], dtype=torch.long, device=device)
    ex_t   = torch.tensor([sample["exercise_idx"]], dtype=torch.long, device=device)

    if ae is not None:
        ae_m = ae.module if hasattr(ae,"module") else ae
        lat  = torch.from_numpy(ae_m.get_latent(sample["keypoints"],device)).unsqueeze(0).to(device)
    else:
        lat_np = safe_np(sample.get("latent", np.zeros(RepTCNAutoEncoder.LATENT_DIM, np.float32)))
        lat    = torch.from_numpy(lat_np).unsqueeze(0).to(device)

    lg, qp, _ = m_(kps_t, adj_t, sc_t, mode_t, ex_t, lat)
    label   = int(lg.argmax(1).item())
    quality = float(torch.sigmoid(qp).item())
    torque  = compute_torque(quality, hw_mode)
    fb      = generate_feedback(label, quality, sample["scalars"])
    hw      = hardware_payload(sample, quality, torque, hw_mode)

    return {
        "rep_id":         sample.get("rep_id","?"),
        "exercise":       sample.get("exercise","unknown"),
        "label":          label,
        "correct":        label == 1,
        "quality_score":  round(quality, 4),
        "feedback":       fb["message"],
        "feedback_short": fb["short"],
        "severity":       fb["severity"],
        "flags":          fb["flags"],
        "hardware":       hw,
        "torque_signal":  torque,
        "mode_name":      HW_MODES[hw_mode]["name"],
        "scalars":        sample["scalars"].tolist(),
    }

