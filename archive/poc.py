class STGCNBlock(nn.Module):
    def __init__(self, c_in, c_out, ks=9, stride=1):
        super().__init__()
        self.gcn = nn.Linear(c_in, c_out)
        self.tcn = nn.Sequential(
            nn.BatchNorm2d(c_out), nn.GELU(),
            nn.Conv2d(c_out, c_out, (ks,1), (stride,1), ((ks-1)//2,0)),
            nn.BatchNorm2d(c_out), nn.Dropout(0.1),
        )
        self.res = (nn.Sequential(nn.Conv2d(c_in,c_out,1,(stride,1)),
                                  nn.BatchNorm2d(c_out))
                    if c_in != c_out or stride != 1 else nn.Identity())
        self.act = nn.GELU()

    def forward(self, x, A):
        B, C, T, V = x.shape
        xs = x.permute(0,2,3,1).contiguous().view(B*T, V, C)
        xs = torch.bmm(A.unsqueeze(0).expand(B*T,-1,-1), xs)
        xs = self.gcn(xs).view(B,T,V,-1).permute(0,3,1,2)
        return self.act(torch.nan_to_num(self.tcn(xs)) +
                        torch.nan_to_num(self.res(x)))

class AttentionPool(nn.Module):
    def __init__(self, ch):
        super().__init__()
        self.score = nn.Linear(ch, 1)

    def forward(self, x):
        xp = x.permute(0,2,3,1)
        w  = torch.softmax(self.score(xp), dim=2)
        return (xp * w).sum(2)

class STGCN(nn.Module):
    DIM = 256

    def __init__(self):
        super().__init__()
        D = self.DIM
        self.norm_in  = nn.LayerNorm(IN_CH * N_JOINTS)
        self.b1       = STGCNBlock(3,   64)
        self.b2       = STGCNBlock(64,  128)
        self.b3       = STGCNBlock(128, D)
        self.pool     = AttentionPool(D)
        self.adj_res  = nn.Parameter(torch.zeros(N_JOINTS, N_JOINTS))

    def forward(self, x, adj):
        A  = adj if adj.dim() == 2 else adj[0]
        A_ = A + torch.tanh(self.adj_res) * 0.1

        B, C, T, V = x.shape
        x  = torch.clamp(x, -5.0, 5.0)
        xf = x.permute(0,2,1,3).reshape(B*T, C*V)
        xf = self.norm_in(xf).view(B,T,C,V).permute(0,2,1,3)

        out = self.b3(self.b2(self.b1(xf, A_), A_), A_)
        return self.pool(out)

class ClinicalTransformer(nn.Module):
    def __init__(self, d=256, heads=8, d_ff=512, drop=0.1, n_layers=3):
        super().__init__()
        pe  = torch.zeros(TARGET_LEN+1, d)
        pos = torch.arange(TARGET_LEN+1).unsqueeze(1).float()
        div = torch.exp(torch.arange(0,d,2).float() * (-np.log(10000.0)/d))
        pe[:,0::2] = torch.sin(pos * div)
        pe[:,1::2] = torch.cos(pos * div)
        self.register_buffer("pe", pe.unsqueeze(0))
        self.cls  = nn.Parameter(torch.randn(1,1,d) * 0.02)
        self.drop = nn.Dropout(drop)
        mk = lambda: nn.TransformerEncoderLayer(
            d, heads, d_ff, drop, batch_first=True, norm_first=True)
        self.layers = nn.ModuleList([mk() for _ in range(n_layers)])

    def forward(self, x):
        B, T, _ = x.shape
        x = torch.cat([self.cls.expand(B,-1,-1), x], 1)
        x = self.drop(x + self.pe[:, :T+1])
        for layer in self.layers:
            x = layer(x)
        return x[:, 0]

class RehabNet(nn.Module):
    _D      = 256
    _N_EX   = N_EX
    _N_MODES= N_MODES
    _LAT_IN = RepTCNAutoEncoder.LATENT_DIM

    def __init__(self):
        super().__init__()
        D = self._D
        self.stgcn     = STGCN()
        self.trans     = ClinicalTransformer(d=D)
        self.bilstm    = nn.LSTM(D, D//2, num_layers=2, batch_first=True,
                                 bidirectional=True, dropout=0.1)
        self.lstm_proj = nn.Sequential(
            nn.Linear(D,D), nn.LayerNorm(D), nn.GELU(), nn.Dropout(0.1))
        self.lat_proj  = nn.Sequential(
            nn.Linear(self._LAT_IN, 64), nn.LayerNorm(64), nn.GELU())
        self.mode_emb  = nn.Embedding(self._N_MODES, 32)
        self.ex_emb    = nn.Embedding(self._N_EX,    16)

        fused = D + D + 64 + 10 + 32 + 16
        self.shared = nn.Sequential(
            nn.Linear(fused, 512), nn.LayerNorm(512), nn.GELU(), nn.Dropout(0.2),
            nn.Linear(512,   256), nn.LayerNorm(256), nn.GELU(), nn.Dropout(0.1),
        )
        self.head_cls  = nn.Linear(256, 2)
        self.head_qual = nn.Linear(256, 1)
        self.head_ex   = nn.Linear(256, self._N_EX)
        self._init()

    def _init(self):
        for m in self.modules():
            if isinstance(m, nn.Linear):
                nn.init.xavier_uniform_(m.weight)
                if m.bias is not None: nn.init.zeros_(m.bias)

    def forward(self, kps, adj, scalars, mode=None, ex_idx=None, latent=None):
        B, dev = kps.shape[0], kps.device
        if mode   is None: mode   = torch.zeros(B, dtype=torch.long, device=dev)
        if ex_idx is None: ex_idx = torch.zeros(B, dtype=torch.long, device=dev)
        if latent is None: latent = torch.zeros(B, self._LAT_IN, device=dev)
        mode   = mode.clamp(0, self._N_MODES - 1)
        ex_idx = ex_idx.clamp(0, self._N_EX   - 1)

        feats         = self.stgcn(kps, adj)
        cls           = self.trans(feats)
        lstm_out, _   = self.bilstm(feats)
        lstm_ctx      = self.lstm_proj(lstm_out.mean(1))
        lat           = self.lat_proj(latent)

        h = self.shared(torch.cat(
            [cls, lstm_ctx, lat, scalars,
             self.mode_emb(mode), self.ex_emb(ex_idx)], dim=1))
        return self.head_cls(h), self.head_qual(h).squeeze(1), self.head_ex(cls)

    def predict_exercise(self, kps, adj):
        self.eval()
        with torch.no_grad():
            feats = self.stgcn(kps, adj)
            cls   = self.trans(feats)
            idx   = int(self.head_ex(cls).argmax(1).item())
        return EXERCISE_LIST[idx], idx

class FocalLoss(nn.Module):
    def __init__(self, gamma=2.0, weight=None):
        super().__init__()
        self.gamma = gamma
        self.w     = weight

    def forward(self, logits, targets):
        ce = F.cross_entropy(logits, targets, weight=self.w, reduction="none")
        return ((1 - torch.exp(-ce)) ** self.gamma * ce).mean()

class UncertaintyLoss(nn.Module):
    def __init__(self, n=3):
        super().__init__()
        self.log_var = nn.Parameter(torch.zeros(n))

    def forward(self, losses):
        total = sum(torch.exp(-self.log_var[i]) * l + self.log_var[i]
                    for i, l in enumerate(losses))
        return total

