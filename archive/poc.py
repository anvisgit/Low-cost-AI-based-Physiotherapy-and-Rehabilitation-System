def safe_np(x, fill=0.0, clip=None, dtype=np.float32):
    x = np.nan_to_num(np.asarray(x, dtype=dtype), nan=fill, posinf=fill, neginf=fill)
    return np.clip(x, -clip, clip).astype(dtype) if clip is not None else x.astype(dtype)

def valid_np(x):
    x = np.asarray(x)
    return x.size > 0 and bool(np.isfinite(x).all())

def smooth(arr, win=7, poly=2):
    arr = safe_np(arr)
    if len(arr) < win + 2:
        return arr
    w = win if win % 2 == 1 else win + 1
    w = max(w, poly + 2 if (poly + 2) % 2 == 1 else poly + 3)
    try:
        return safe_np(savgol_filter(arr, w, poly))
    except Exception:
        return arr

def resample_1d(arr, n):
    arr = safe_np(arr)
    if len(arr) == n:
        return arr
    if len(arr) < 2:
        return np.zeros(n, dtype=np.float32)
    return safe_np(np.interp(np.linspace(0,1,n), np.linspace(0,1,len(arr)), arr))

def fill_missing(kps):
    kps = safe_np(kps)
    T, J, C = kps.shape
    for j in range(J):
        opp = j + 3 if j < 3 else j - 3
        for c in range(C):
            col = kps[:, j, c]
            bad = (~np.isfinite(col)) | (col == 0.0)
            if bad.all():
                kps[:, j, c] = kps[:, opp, c]
            elif bad.any() and (~bad).sum() >= 2:
                f = interp1d(np.where(~bad)[0], col[~bad],
                             bounds_error=False, fill_value="extrapolate")
                kps[:, j, c] = f(np.arange(T))
    return safe_np(kps)

def normalise_kps(kps):
    kps = safe_np(kps)
    hip = ((kps[:,0] + kps[:,3]) / 2.0).mean(0)
    kps = kps - hip
    sl  = np.mean(np.linalg.norm(kps[:,0] - kps[:,2], axis=1))
    sr  = np.mean(np.linalg.norm(kps[:,3] - kps[:,5], axis=1))
    sc  = (sl + sr) / 2.0
    if not (np.isfinite(sc) and sc > 1e-4):
        sc = 1.0
    return safe_np(np.clip(kps / sc, -5.0, 5.0), clip=5.0)

