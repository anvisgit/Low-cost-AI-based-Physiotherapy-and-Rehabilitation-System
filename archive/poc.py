def ps1_video_to_df(video_path, patient_id, exercise="unknown",
                    session="1", label="unknown"):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise FileNotFoundError(f"Cannot open: {video_path}")

    fps_v = cap.get(cv2.CAP_PROP_FPS) or FPS
    _ensure_mp()

    import mediapipe as mp
    from mediapipe.tasks import python as _mpt
    from mediapipe.tasks.python import vision as _mpv

    opts = _mpv.PoseLandmarkerOptions(
        base_options=_mpt.BaseOptions(model_asset_path=MP_MODEL_PATH),
        running_mode=_mpv.RunningMode.VIDEO,
        num_poses=1,
        min_pose_detection_confidence=0.5,
        min_pose_presence_confidence=0.5,
        min_tracking_confidence=0.5,
        output_segmentation_masks=False,
    )
    step_ms = int(1000.0 / fps_v)
    rows, fi, det = [], 0, 0

    with _mpv.PoseLandmarker.create_from_options(opts) as pose:
        while True:
            ok, frame = cap.read()
            if not ok: break
            fi += 1
            h, w = frame.shape[:2]
            if w > 640:
                frame = cv2.resize(frame, (640, int(h*640/w)))
            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            res = pose.detect_for_video(
                mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb), fi*step_ms)
            row = dict(subject_id=patient_id, session=session, label=label,
                       frame_id=fi, time_s=round(fi/fps_v, 4), detection=0)
            row.update({c: float("nan") for c in _JCOLS})
            if res.pose_landmarks:
                det += 1; row["detection"] = 1
                row.update(_extract_row(res.pose_landmarks[0]))
            rows.append(row)
    cap.release()
    if fi == 0: raise ValueError("Empty video")

    pct = 100 * det / fi
    print(f"  PS1: {fi} frames  detection={pct:.0f}%")
    if pct < 20: print("  WARNING: low detection - check lighting / camera angle")

    df = (pd.DataFrame(rows, columns=_BCOLS+_JCOLS)
            .loc[lambda d: d["detection"]==1]
            .reset_index(drop=True))

    for ax in "xyz":
        mid = (df[f"HipLeft_{ax}"] + df[f"HipRight_{ax}"]) / 2.0
        for jn in JOINT_NAMES: df[f"{jn}_{ax}"] -= mid
    for h,k,a in [("HipLeft","KneeLeft","AnkleLeft"),
                  ("HipRight","KneeRight","AnkleRight")]:
        for ax in "xyz":
            sc = np.sqrt(((df[f"{h}_{ax}"]-df[f"{k}_{ax}"])**2).mean()) + EPS
            for jn in [h,k,a]: df[f"{jn}_{ax}"] /= sc

    return df.ffill().bfill().fillna(0.0)

def ps1_df_to_samples(df, patient_id, ae=None, exercise="unknown",
                       label=-1, device=DEVICE):
    xyz_c    = [f"{j}_{ax}" for j in JOINT_NAMES for ax in "xyz"]
    kps_full = df[xyz_c].values.astype(np.float32).reshape(len(df), N_JOINTS, 3)

    if ae is not None:
        ae_m     = ae.module if hasattr(ae,"module") else ae
        rep_list = ae_m.segment_reps(kps_full, exercise=exercise, device=device)
    else:
        angs   = knee_angles(kps_full if kps_full.ndim==3 else
                             process_keypoints(kps_full), "L")
        angs   = smooth(angs)
        md     = EX_MIN_DIST.get(exercise, 50)
        peaks, _ = find_peaks(-angs, distance=md, prominence=md*0.3)
        bounds = [0]+[(peaks[i]+peaks[i+1])//2 for i in range(len(peaks)-1)]+[len(angs)]
        rep_list = [kps_full[bounds[i]:bounds[i+1]]
                    for i in range(len(bounds)-1)
                    if bounds[i+1]-bounds[i] >= MIN_FRAMES] or [kps_full]

    ex_idx  = EX2IDX.get(exercise, EX2IDX["unknown"])
    samples = []
    for i, raw in enumerate(rep_list):
        try:
            kps = process_keypoints(raw)
            lat = ((ae.module if hasattr(ae,"module") else ae).get_latent(kps, device)
                   if ae is not None
                   else np.zeros(RepTCNAutoEncoder.LATENT_DIM, np.float32))
            samples.append({
                "keypoints":    kps,
                "adj":          ADJ,
                "scalars":      extract_scalars(kps),
                "latent":       lat,
                "label":        max(label, 0),
                "quality":      float(max(label, 0)),
                "exercise":     exercise,
                "exercise_idx": ex_idx,
                "subject":      patient_id,
                "source":       "patient_video",
                "rep_id":       f"{patient_id}_r{i+1}",
            })
        except Exception as e:
            print(f"  Rep {i+1} skipped: {e}")

    print(f"  Bridge: {len(rep_list)} segments -> {len(samples)} valid")
    return samples

