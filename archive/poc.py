# Generate rehabilitation metrics

import json
import numpy as np

def compute_rehabilitation_metrics(predictions):
    pred_values = []
    for p in predictions:
        pred = p["prediction"]
        if isinstance(pred, dict) and "class" in pred:
            pred_values.append(pred["class"])
        elif isinstance(pred, (int, float)):
            pred_values.append(pred)
        elif isinstance(pred, str):
            pred_values.append(pred)

    total = len(pred_values)
    if total == 0:
        return {"error": "No predictions to evaluate."}

    if all(isinstance(v, (int, float)) for v in pred_values):
        rehab_metrics = {
            "total_readings": total,
            "mean_prediction": float(np.mean(pred_values)),
            "std_prediction": float(np.std(pred_values)),
            "min_prediction": float(np.min(pred_values)),
            "max_prediction": float(np.max(pred_values)),
        }
    else:
        from collections import Counter
        counts = Counter(pred_values)
        rehab_metrics = {
            "total_readings": total,
            "class_distribution": dict(counts),
            "most_common_class": counts.most_common(1)[0][0],
        }

    return rehab_metrics

rehab_metrics = compute_rehabilitation_metrics(predictions)
