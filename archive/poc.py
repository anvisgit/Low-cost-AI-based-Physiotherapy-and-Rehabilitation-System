        tr, te = loso_split(samples, subj)

        print("\n[AE] Training on fold training data...")
        ae = train_ae_on_fold(tr, device, n_epochs=AE_EPOCHS)

        tr = attach_latents(tr, ae, device)
        te = attach_latents(te, ae, device)

        tl, vl = build_loaders(tr, te, bs)
        cw     = class_weights(tr, device)
        print(f"  class weights: incorrect={cw[0]:.3f}  correct={cw[1]:.3f}")

        model = RehabNet().to(device)
        if N_GPU > 1:
            print(f"  DataParallel across {N_GPU} GPUs")
            model = nn.DataParallel(model)

        focal  = FocalLoss(gamma=2.0, weight=cw)
        unc    = UncertaintyLoss(n=3).to(device)
        params = list(model.parameters()) + list(unc.parameters())
        opt    = torch.optim.AdamW(params, lr=lr, weight_decay=1e-4)
        sched  = torch.optim.lr_scheduler.OneCycleLR(
            opt, max_lr=lr, steps_per_epoch=len(tl),
            epochs=n_epochs, pct_start=0.1, anneal_strategy="cos")
        scaler = GradScaler()

        best_f1, best_state, no_imp = 0.0, None, 0

        for ep in range(n_epochs):
            loss = _train_epoch(model, tl, opt, sched, scaler,
                                device, focal, unc, ep=ep)

            if (ep+1) % 5 == 0:
                model.eval(); pl, ll = [], []
                with torch.no_grad():
                    for b in vl:
                        kps    = b["keypoints"].to(device)
                        sc     = b["scalars"].to(device)
                        ex_idx = b["ex_idx"].to(device)
                        lat    = b["latent"].to(device)
                        adj    = b["adj"].to(device)
                        lbl    = b["label"]
                        good   = (torch.isfinite(kps).flatten(1).all(1) &
                                  torch.isfinite(sc).all(1))
                        if good.sum() == 0: continue
                        kps,sc,ex_idx,lat,adj = [t[good] for t in (kps,sc,ex_idx,lat,adj)]
                        lbl = lbl[good.cpu()]
                        mode = torch.zeros(kps.shape[0], dtype=torch.long, device=device)
                        m_   = model.module if hasattr(model,"module") else model
                        lg,_,_ = m_(kps, adj, sc, mode, ex_idx, lat)
                        pl.extend(lg.argmax(1).cpu().numpy())
                        ll.extend(lbl.numpy())
                model.train()

                vf1   = f1_score(ll, pl, average="macro", zero_division=0)
                lr_now = opt.param_groups[0]["lr"]
                print(f"  ep{ep+1:3d} | loss={loss:.4f} | lr={lr_now:.2e} | val_f1={vf1:.3f}")

                if vf1 > best_f1:
                    best_f1 = vf1
                    m_      = model.module if hasattr(model,"module") else model
                    best_state = copy.deepcopy(m_.state_dict())
                    no_imp  = 0
                else:
                    no_imp += 1
                    if no_imp >= patience:
                        print(f"  Early stop at ep{ep+1}"); break

        if best_state:
            m_ = model.module if hasattr(model,"module") else model
            m_.load_state_dict(best_state)

        if best_f1 > best_f1_overall:
            best_f1_overall = best_f1
            m_ = model.module if hasattr(model,"module") else model
            best_state_overall = copy.deepcopy(m_.state_dict())

        print(f"\n── Eval: {subj}  (best_val_f1={best_f1:.3f}) ──")
        results.append(_evaluate(model, vl, device))

