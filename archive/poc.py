class _TCNRes(nn.Module):
    def __init__(self, ch, ks=5, dilation=1, drop=0.1):
        super().__init__()
        pad = (ks - 1) * dilation
        self.c1   = nn.Conv1d(ch, ch, ks, padding=pad, dilation=dilation)
        self.c2   = nn.Conv1d(ch, ch, ks, padding=pad, dilation=dilation)
        self.norm = nn.GroupNorm(min(8, ch), ch)
        self.drop = nn.Dropout(drop)
        self.act  = nn.GELU()

    def forward(self, x):
        T = x.shape[-1]
        y = self.drop(self.act(self.c1(x)[:, :, :T]))
        y = self.c2(y)[:, :, :T]
        return self.norm(self.act(y + x))

class RepTCNAutoEncoder(nn.Module):
    LATENT_DIM = 128

    def __init__(self):
        super().__init__()
        B, L = 64, self.LATENT_DIM

        self.enc_proj = nn.Conv1d(AE_CH, B, 1)
        self.enc = nn.ModuleList([
            nn.Sequential(_TCNRes(B, dilation=1), _TCNRes(B, dilation=2),
                          nn.Conv1d(B, B*2, 3, stride=2, padding=1), nn.GELU()),
            nn.Sequential(_TCNRes(B*2, dilation=1), _TCNRes(B*2, dilation=4),
                          nn.Conv1d(B*2, L, 3, stride=2, padding=1), nn.GELU()),
        ])
        self.bottleneck = nn.Sequential(
            _TCNRes(L,dilation=1), _TCNRes(L,dilation=2), _TCNRes(L,dilation=4))
        self.dec = nn.ModuleList([
            nn.Sequential(nn.ConvTranspose1d(L, B*2, 4, stride=2, padding=1),
                          nn.GELU(), _TCNRes(B*2, dilation=1)),
            nn.Sequential(nn.ConvTranspose1d(B*2, B, 4, stride=2, padding=1),
                          nn.GELU(), _TCNRes(B, dilation=1)),
        ])
        self.out_proj = nn.Conv1d(B, AE_CH, 1)

    def encode(self, x):
        z = self.enc_proj(x)
        for block in self.enc:
            z = block(z)
        return self.bottleneck(z)

    def decode(self, z, T):
        for block in self.dec:
            z = block(z)
        z = self.out_proj(z)
        if z.shape[-1] > T:    z = z[:, :, :T]
        elif z.shape[-1] < T:  z = F.pad(z, (0, T - z.shape[-1]))
        return z

    def forward(self, x):
        z = self.encode(x)
        return self.decode(z, x.shape[-1]), z

    @torch.no_grad()
    def get_latent(self, kps_np, device=None):
        device = device or DEVICE
        self.eval()
        x  = safe_np(kps_np).reshape(TARGET_LEN, -1).T
        xt = torch.from_numpy(x[None]).float().to(device)
        z  = self.encode(xt)
        return z.mean(-1).squeeze(0).cpu().numpy()

    @torch.no_grad()
    def segment_reps(self, kps_seq, exercise="unknown", device=None):
        device = device or DEVICE
        self.eval()
        T_raw   = len(kps_seq)
        x_full  = safe_np(kps_seq).reshape(T_raw, -1).T
        errors  = np.zeros(T_raw, dtype=np.float32)
        counts  = np.zeros(T_raw, dtype=np.float32)

        for st in range(0, max(T_raw - AE_WIN + 1, 1), AE_STRIDE):
            en  = min(st + AE_WIN, T_raw)
            w   = x_full[:, st:en].copy()
            if w.shape[1] < AE_WIN:
                w = np.pad(w, ((0,0),(0, AE_WIN - w.shape[1])))
            wt  = torch.from_numpy(w[None]).float().to(device)
            rec, _ = self(wt)
            L   = en - st
            err = (F.mse_loss(rec[:,:,:L], wt[:,:,:L], reduction="none")
                   .mean(1).squeeze().cpu().numpy())
            if err.ndim == 0:
                err = np.array([float(err)])
            errors[st:en] += err[:L]
            counts[st:en] += 1

        errors /= np.maximum(counts, 1)
        errors  = safe_np(smooth(errors, win=15))

        min_d = EX_MIN_DIST.get(exercise, 50)
        prom  = max(float(errors.std()) * 0.5, 0.005)
        peaks, _ = find_peaks(errors, distance=min_d, prominence=prom)

        bounds = [0] + list(peaks) + [T_raw]
        reps   = [kps_seq[bounds[i]:bounds[i+1]]
                  for i in range(len(bounds)-1)
                  if bounds[i+1]-bounds[i] >= MIN_FRAMES]
        return reps if reps else [kps_seq]


