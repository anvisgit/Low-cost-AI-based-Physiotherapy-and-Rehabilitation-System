    best_loss, best_state = float("inf"), None

    for ep in range(n_epochs):
        ae.train(); total = 0.0
        for (xb,) in dl:
            xb = xb.to(device)
            opt.zero_grad(set_to_none=True)
            with autocast():
                rec, _ = ae(xb)
                loss   = F.mse_loss(rec, xb)
            scaler.scale(loss).backward()
            scaler.step(opt); scaler.update()
            total += loss.item()
        sched.step()
        avg = total / len(dl)
        if avg < best_loss:
            best_loss  = avg
            m_ = ae.module if hasattr(ae,"module") else ae
            best_state = copy.deepcopy(m_.state_dict())
        if (ep+1) % 10 == 0:
            print(f"    AE ep{ep+1:3d} | loss={avg:.5f}")

    m_ = ae.module if hasattr(ae,"module") else ae
    m_.load_state_dict(best_state)
    print(f"  AE trained ✓  best_loss={best_loss:.5f}")
    return ae

