import numpy as np

def compute_exercise_correctness_score(predictions):
    scores = []
    for p in predictions:
        pred = p["prediction"]
        if isinstance(pred, dict):
            if "confidence" in pred:
                scores.append(float(pred["confidence"]))
            elif "correctness" in pred:
                scores.append(float(pred["correctness"]))
            elif "score" in pred:
                scores.append(float(pred["score"]))
        elif isinstance(pred, (int, float)):
            scores.append(float(pred))

    if not scores:
        return {
            "exercise_correctness_score": None,
            "note": "No numeric confidence or score field found in predictions.",
        }

    return {
        "exercise_correctness_score": round(float(np.mean(scores)), 4),
        "min_score": round(float(np.min(scores)), 4),
        "max_score": round(float(np.max(scores)), 4),
        "std_score": round(float(np.std(scores)), 4),
        "num_evaluated": len(scores),
    }

