# Scheduler: auto-retrain on new features, auto-deploy on new model

import os
import time
import json
import pickle
import glob
import hashlib

def file_hash(path):
    h = hashlib.md5()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()

def run_scheduler(poll_interval_seconds=30, max_cycles=None):
    print(f"Scheduler started. Polling every {poll_interval_seconds}s.")

    features_path = "project/shared/features/features.parquet"
    models_dir = "project/shared/models"
    supported_ext = ["*.pt", "*.pth", "*.onnx", "*.pkl"]

    last_features_hash = None
    last_model_hash = None
    cycle = 0

    while True:
        cycle += 1
        if max_cycles and cycle > max_cycles:
            print("Max cycles reached. Scheduler stopping.")
            break

        print(f"\n[Scheduler] Cycle {cycle} at {time.strftime('%H:%M:%S')}")

        # Check for new features
        if os.path.exists(features_path):
            current_hash = file_hash(features_path)
            if current_hash != last_features_hash:
                print("[Scheduler] New features detected. Triggering PS2 retraining...")
                last_features_hash = current_hash
                try:
                    import sys
                    import pandas as pd
                    sys.path.insert(0, "project/ps2")
                    from ps2_train import train_model
                    df = pd.read_parquet(features_path)
                    model = train_model(df)
                    model_path = os.path.join(models_dir, "model.pkl")
                    with open(model_path, "wb") as f:
                        pickle.dump(model, f)
                    print(f"[Scheduler] Retrain complete. Model saved: {model_path}")
                    last_model_hash = file_hash(model_path)
                except Exception as e:
                    print(f"[Scheduler] Retrain failed: {e}")

        # Check for new model
        found_models = []
        for ext in supported_ext:
            found_models.extend(glob.glob(os.path.join(models_dir, ext)))
        if found_models:
            current_model_hash = file_hash(found_models[0])
            if current_model_hash != last_model_hash:
                print("[Scheduler] New model detected. Deploying to PS3 inference engine...")
                last_model_hash = current_model_hash
                try:
                    sys.path.insert(0, "project/ps3")
                    from ps3_inference import InferenceEngine
                    engine = InferenceEngine()
                    engine.load_model(found_models[0])
                    print(f"[Scheduler] PS3 engine updated with: {found_models[0]}")
                except Exception as e:
                    print(f"[Scheduler] PS3 deploy failed: {e}")

        time.sleep(poll_interval_seconds)

# Error handling utilities

import os
import json
import traceback

class PipelineError(Exception):
    pass

def safe_load_features(features_path, metadata_path):
    if not os.path.exists(features_path):
        raise PipelineError(f"Missing feature file: {features_path}")
    if not os.path.exists(metadata_path):
        raise PipelineError(f"Missing metadata file: {metadata_path}")
    try:
        import pandas as pd
        df = pd.read_parquet(features_path)
    except Exception as e:
        raise PipelineError(f"Corrupt features file ({features_path}): {e}")
    try:
        with open(metadata_path, "r") as f:
            metadata = json.load(f)
    except json.JSONDecodeError as e:
        raise PipelineError(f"Corrupt metadata JSON ({metadata_path}): {e}")
    return df, metadata

def safe_load_model(models_dir):
    import glob, pickle
    supported_ext = ["*.pt", "*.pth", "*.onnx", "*.pkl"]
    found = []
    for ext in supported_ext:
        found.extend(glob.glob(os.path.join(models_dir, ext)))
    if not found:
        raise PipelineError(f"No model file found in {models_dir}. Run PS2 training first.")
    model_path = found[0]
    try:
        if model_path.endswith(".pkl"):
            with open(model_path, "rb") as f:
                pickle.load(f)
    except Exception as e:
        raise PipelineError(f"Corrupt model file ({model_path}): {e}")
    return model_path

