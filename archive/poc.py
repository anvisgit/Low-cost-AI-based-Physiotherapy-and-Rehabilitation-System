_JOINT_RE = re.compile(
    r'\((\w+),(Tracked|Inferred|NotTracked),([-\d.]+),([-\d.]+),([-\d.]+)'
)

def parse_raw_file(filepath):
    """Parse one RawData .txt → ndarray (n_frames, 25, 3) or None."""
    frames = []
    with open(filepath) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("Version"):
                continue
            joints = _JOINT_RE.findall(line)
            if len(joints) < 25:
                continue
            frame = np.array(
                [[float(x), float(y), float(z)] for (_, _, x, y, z) in joints],
                dtype=np.float32
            )
            frames.append(frame)
    return np.stack(frames) if frames else None


def center_on_spine(seq):
    """
    Subtract SpineBase (joint 0) from every joint so the skeleton is
    root-relative → position-invariant across patients and camera distances.
    (n_frames, 25, 3) → (n_frames, 25, 3)
    """
    return seq - seq[:, 0:1, :]


def resample_sequence(seq, n_out=TARGET_FRAMES):
    """
    Cubic interpolation along the time axis to a fixed frame count.
    (n_frames, J, 3) → (n_out, J, 3)
    """
    n_in = seq.shape[0]
    if n_in == n_out:
        return seq
    t_in  = np.linspace(0, 1, n_in)
    t_out = np.linspace(0, 1, n_out)
    out   = np.zeros((n_out, seq.shape[1], 3), dtype=np.float32)
    for j in range(seq.shape[1]):
        for ax in range(3):
            out[:, j, ax] = interp1d(t_in, seq[:, j, ax], kind="cubic")(t_out)
    return out

