def knee_angles(kps, side="L"):
    h, k, a = ((kps[:,0],kps[:,1],kps[:,2]) if side=="L"
               else (kps[:,3],kps[:,4],kps[:,5]))
    v1, v2 = h - k, a - k
    cos = (np.sum(v1*v2,-1) /
           (np.linalg.norm(v1,-1) * np.linalg.norm(v2,-1) + EPS))
    return np.degrees(np.arccos(np.clip(cos, -1, 1)))

