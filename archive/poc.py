# Generate ROM (Range of Motion) score

import numpy as np
import json

def compute_rom_score(sensor_data):
    rom_scores = {}
    angle_keys = [k for k in sensor_data[0].keys() if any(
        kw in k.lower() for kw in ["angle", "pitch", "roll", "yaw", "rom", "flex", "ext"]
    )]

    if not angle_keys:
        # Ensure rom_score is always a dictionary, even if no angle keys are found
        return {
            "rom_score": None,
            "note": (
                "No angle/ROM fields detected in sensor data. "
                "Expected keys containing: angle, pitch, roll, yaw, rom, flex, ext."
            ),
        }

    for key in angle_keys:
        values = []
        for reading in sensor_data:
            if key in reading and reading[key] is not None:
                values.append(float(reading[key]))
        if values:
            rom_scores[key] = {
                "min_deg": round(min(values), 2),
                "max_deg": round(max(values), 2),
                "range_deg": round(max(values) - min(values), 2),
                "mean_deg": round(float(np.mean(values)), 2),
            }

    return {
        "rom_scores_by_axis": rom_scores,
        "total_axes_evaluated": len(rom_scores),
    }

rom_score = compute_rom_score(sensor_data)
print("ROM scores:")
print(json.dumps(rom_score, indent=2))

