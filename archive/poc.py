def _train_epoch(model, loader, opt, sched, scaler, device, focal, unc, ep=0):
    model.train()
    tot, used, skip = 0.0, 0, 0

    for b in loader:
        kps    = b["keypoints"].to(device)
        lbl    = b["label"].to(device)
        qual   = b["quality"].to(device)
        sc     = b["scalars"].to(device)
        ex_idx = b["ex_idx"].to(device)
        lat    = b["latent"].to(device)
        adj    = b["adj"].to(device)

        good = (torch.isfinite(kps).flatten(1).all(1) &
                torch.isfinite(sc).all(1) &
                torch.isfinite(qual))
        if not good.all():
            kps,lbl,qual,sc,ex_idx,lat,adj = [t[good] for t in (kps,lbl,qual,sc,ex_idx,lat,adj)]
        if kps.shape[0] == 0: skip += 1; continue

        mode = torch.zeros(kps.shape[0], dtype=torch.long, device=device)
        opt.zero_grad(set_to_none=True)

        with autocast():
            lg, qp, ex_lg = model(kps, adj, sc, mode, ex_idx, lat)
            if not (torch.isfinite(lg).all() and torch.isfinite(qp).all()):
                skip += 1; continue
            l_cls  = focal(lg, lbl)
            l_qual = F.mse_loss(torch.sigmoid(qp), qual.clamp(0,1))
            l_ex   = F.cross_entropy(ex_lg, ex_idx)
            loss   = unc([l_cls, l_qual, l_ex])

        if not torch.isfinite(loss): skip += 1; continue
        scaler.scale(loss).backward()
        scaler.unscale_(opt)
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        scaler.step(opt); scaler.update()
        sched.step()
        tot += loss.item(); used += 1

    if skip: print(f"  ep{ep}: {skip} batches skipped")
    return tot / max(used, 1)

@torch.no_grad()
def _evaluate(model, loader, device):
    model.eval()
    preds, labels, quals, qpreds = [], [], [], []

    for b in loader:
        kps    = b["keypoints"].to(device)
        sc     = b["scalars"].to(device)
        ex_idx = b["ex_idx"].to(device)
        qual   = b["quality"].to(device)
        lbl    = b["label"].to(device)
        lat    = b["latent"].to(device)
        adj    = b["adj"].to(device)
        good   = (torch.isfinite(kps).flatten(1).all(1) &
                  torch.isfinite(sc).all(1))
        if good.sum() == 0: continue
        kps,sc,ex_idx,qual,lbl,lat,adj = [t[good] for t in (kps,sc,ex_idx,qual,lbl,lat,adj)]
        mode = torch.zeros(kps.shape[0], dtype=torch.long, device=device)
        m_   = model.module if hasattr(model,"module") else model
        lg, qp, _ = m_(kps, adj, sc, mode, ex_idx, lat)
        preds.extend(lg.argmax(1).cpu().numpy())
        labels.extend(lbl.cpu().numpy())
        quals.extend(qual.cpu().numpy())
        qpreds.extend(torch.sigmoid(qp).cpu().numpy())

    if not labels: return {"acc":0.0,"f1":0.0,"quality_r":0.0}
    acc = accuracy_score(labels, preds)
    f1  = f1_score(labels, preds, average="macro", zero_division=0)
    r   = (pearsonr(quals, qpreds)[0]
           if len(set(float(q) for q in quals)) > 1 else 0.0)
    print(classification_report(labels, preds, labels=[0, 1],
          target_names=["incorrect","correct"], zero_division=0))
    print(f"  Quality Pearson r={r:.3f}")
    return {"acc":acc,"f1":f1,"quality_r":r}

